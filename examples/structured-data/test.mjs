import assert from 'node:assert/strict';
import addon from './index.mjs';
import { createRequire } from 'node:module';
const cjs = createRequire(import.meta.url)('./index.cjs');
for (const name of Object.keys(addon)) assert.equal(cjs[name], addon[name]);
assert.deepEqual(addon.profile({ name: 'Moon' }), { name: 'Moon', age: null });
assert.deepEqual(addon.event({ tag: 'Message', args: ['hello'] }), { tag: 'Message', args: ['hello'] });
assert.throws(() => addon.profile({ age: 1 }));
assert.deepEqual(addon.records({ moon: { name: 'Moon' } }), { moon: { name: 'Moon', age: null } });
assert.deepEqual(addon.json({ nested: [1, 'two', null, true] }), { nested: [1, 'two', null, true] });
assert.throws(() => addon.json({ unsupported: 1n }));
assert.deepEqual(addon.tuple(['Moon', 2, undefined]), ['Moon', 2, null]);
assert.throws(() => addon.tuple(['Moon', 2]));
assert.equal(addon.tomorrow(new Date('2026-01-01T00:00:00Z')).toISOString(), '2026-01-02T00:00:00.000Z');
assert.throws(() => addon.tomorrow(new Date(NaN)));
const symbol = Symbol('local');
assert.equal(addon.symbol(symbol), symbol);
assert.deepEqual([...addon.set(new Set([3, 1, 3]))], [3, 1]);
let closed = false;
function* source() { try { yield 7; yield 8; } finally { closed = true; } }
assert.equal(addon.first(source()), 7);
assert.equal(closed, true);
assert.equal(addon.first([]), null);
assert.deepEqual([...addon.range(3)], [0, 1, 2]);
console.log('structured-data passed');
